const seed = async () => {
  await mongoose.connect(MONGO_URI, {
    serverSelectionTimeoutMS: 30000,
  });

  // Clear existing data
  await User.deleteMany({});
  await Product.deleteMany({});
  await Coupon.deleteMany({});

  // Create users (hash passwords)
  const createdUsers = [];
  for (const u of users) {
    const hash = await bcrypt.hash(u.password, 12);
    const user = await User.create({
      name: u.name,
      email: u.email,
      password: hash,
      role: u.role,
      shopName: u.shopName,
    });
    createdUsers.push(user);
  }

  const [customer, seller1, seller2, admin] = createdUsers;

  // Assign sellers to products (distribute between seller1 and seller2)
  products.forEach((p, i) => {
    p.seller = i % 2 === 0 ? seller1._id : seller2._id;
  });

  // Create products
  await Product.insertMany(products);

  // Create coupons
  await Coupon.insertMany(coupons);

  console.log('✅ Seed complete');
  console.log(`Users: ${createdUsers.length} (customer, seller1, seller2, admin)`);
  console.log(`Products: ${products.length}`);
  console.log(`Coupons: ${coupons.length}`);
  console.log('');
  console.log('Demo credentials:');
  console.log('  customer@ironnest.test / password123 (customer)');
  console.log('  seller1@ironnest.test / password123 (seller — Strength & Iron Co.)');
  console.log('  seller2@ironnest.test / password123 (seller — Cardio Lab)');
  console.log('  admin@ironnest.test / password123 (admin)');

  await mongoose.disconnect();
};

seed().catch((err) => {
  console.error('❌ Seed failed:', err.message);
  process.exit(1);
});
